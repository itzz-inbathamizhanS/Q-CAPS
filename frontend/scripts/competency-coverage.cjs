// Competency tagging coverage report.
//
//   node scripts/competency-coverage.cjs            # print the report
//   node scripts/competency-coverage.cjs --write    # also write docs/curriculum/COMPETENCY_COVERAGE.md
//
// Per module: items, tagged items, and which competencies reach the "known" threshold (min_items_for_known in
// competency_model.json). Per competency: items by depth group and tagged practicals, because the level rules need
// Aware/Explain items, Apply items, Analyse items and a passed practical. Drafted tags (tag_status
// "proposed-unreviewed") are counted separately from reviewed ones; a draft is never reported as reviewed.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../../content');
const OUT = path.resolve(__dirname, '../../docs/curriculum/COMPETENCY_COVERAGE.md');

function load() {
  const model = JSON.parse(fs.readFileSync(path.join(ROOT, 'curriculum', 'competency_model.json'), 'utf8'));
  const modules = [];
  for (const dir of fs.readdirSync(path.join(ROOT, 'Quizzes')).sort()) {
    const full = path.join(ROOT, 'Quizzes', dir);
    if (!fs.statSync(full).isDirectory()) continue;
    for (const file of fs.readdirSync(full).filter((f) => f.endsWith('.json')).sort()) {
      const quiz = JSON.parse(fs.readFileSync(path.join(full, file), 'utf8'));
      // Track A files carry the status at file level; drafted items in other tracks carry it per item.
      const fileStatus = quiz.tagging_status ?? null;
      modules.push({
        module_id: quiz.module_id,
        items: quiz.questions.map((q) => ({
          id: q.id, competency_id: q.competency_id ?? null, depth: q.depth ?? null,
          status: q.tag_status ?? (q.competency_id ? fileStatus ?? 'unknown' : null),
        })),
      });
    }
  }
  const labs = JSON.parse(fs.readFileSync(path.join(ROOT, 'Labs', 'escape_room_scenarios.json'), 'utf8')).scenarios
    .map((s) => ({ kind: 'lab', id: s.id, competencies: s.competencies || [], status: s.tag_status ?? null }));
  const missions = fs.readdirSync(path.join(ROOT, 'Mission')).filter((f) => /^mission_.*\.json$/.test(f)).sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'Mission', f), 'utf8')))
    .map((m) => ({ kind: 'mission', id: m.mission_id, competencies: m.competencies || [], status: m.tag_status ?? null }));
  return { model, modules, practicals: [...labs, ...missions] };
}

const GROUP = { Aware: 'aware_explain', Explain: 'aware_explain', Apply: 'apply', Analyse: 'analyse' };

function report({ model, modules, practicals }) {
  const threshold = model.capability_levels.min_items_for_known;
  const competencies = model.domains.flatMap((d) => d.competencies.map((c) => ({ id: c.id, name: c.name })));
  const per = Object.fromEntries(competencies.map((c) => [c.id, { aware_explain: 0, apply: 0, analyse: 0, reviewed: 0, practicals: [] }]));
  const lines = [];
  const all = modules.flatMap((m) => m.items);
  const tagged = all.filter((i) => i.competency_id);
  const reviewed = tagged.filter((i) => i.status === 'reviewed');
  const noCompetency = all.filter((i) => i.status === 'no-competency');
  const untagged = all.filter((i) => !i.competency_id && i.status !== 'no-competency');

  lines.push('# Competency tagging coverage', '');
  lines.push(`Generated by \`frontend/scripts/competency-coverage.cjs\` from \`content/\`. Competency model version ${model.version} (${model.status}).`);
  lines.push(`A competency is "known" for a learner only with at least ${threshold} scored items (min_items_for_known), so a competency`);
  lines.push(`with fewer than ${threshold} items in the bank can never leave Unknown.`, '');
  lines.push('**Every tag counted here is proposed-unreviewed unless the Reviewed column says otherwise. Drafted tags are not validated.**', '');
  lines.push('## Summary', '');
  lines.push('| | Count |', '|---|---|');
  lines.push(`| Quiz items | ${all.length} |`);
  lines.push(`| Tagged (competency + depth) | ${tagged.length} |`);
  lines.push(`| of which reviewed | ${reviewed.length} |`);
  lines.push(`| Marked no-competency (tests course structure, not a skill) | ${noCompetency.length} |`);
  lines.push(`| Untagged | ${untagged.length} |`);
  lines.push(`| Practicals (labs + missions) | ${practicals.length} |`);
  lines.push(`| Tagged practicals | ${practicals.filter((p) => p.competencies.length).length} |`, '');

  lines.push('## Per module', '');
  lines.push(`| Module | Items | Tagged | Reviewed | Competencies with >= ${threshold} items |`, '|---|---|---|---|---|');
  for (const m of modules) {
    const counts = {};
    for (const i of m.items.filter((x) => x.competency_id)) counts[i.competency_id] = (counts[i.competency_id] || 0) + 1;
    const known = Object.entries(counts).filter(([, n]) => n >= threshold).map(([c, n]) => `${c} (${n})`).sort();
    const t = m.items.filter((i) => i.competency_id);
    lines.push(`| ${m.module_id} | ${m.items.length} | ${t.length} | ${t.filter((i) => i.status === 'reviewed').length} | ${known.join(', ') || 'none'} |`);
  }
  lines.push('');

  for (const i of tagged) {
    const p = per[i.competency_id];
    if (!p) continue; // the validator reports unknown competencies
    p[GROUP[i.depth]] += 1;
    if (i.status === 'reviewed') p.reviewed += 1;
  }
  for (const pr of practicals) for (const c of pr.competencies) per[c.id]?.practicals.push(`${pr.id} (${c.depth})`);

  lines.push('## Per competency', '');
  lines.push('Items by depth group across the whole bank. Developing needs Aware/Explain items, Proficient needs Apply items and a');
  lines.push('practical, Advanced needs Analyse items (competency_model.json, capability_levels).', '');
  lines.push(`| Competency | Aware/Explain | Apply | Analyse | Reviewed | Practicals | Gaps |`, '|---|---|---|---|---|---|---|');
  for (const c of competencies) {
    const p = per[c.id];
    const gaps = [];
    if (p.aware_explain + p.apply + p.analyse < threshold) gaps.push(`fewer than ${threshold} items`);
    if (p.apply === 0) gaps.push('no Apply items');
    if (p.practicals.length === 0) gaps.push('no practical');
    lines.push(`| ${c.id} ${c.name} | ${p.aware_explain} | ${p.apply} | ${p.analyse} | ${p.reviewed} | ${p.practicals.length} | ${gaps.join('; ') || '-'} |`);
  }
  lines.push('');

  lines.push('## Items without a competency', '');
  lines.push(`no-competency: ${noCompetency.map((i) => i.id).join(', ') || 'none'}`, '');
  lines.push(`untagged: ${untagged.map((i) => i.id).join(', ') || 'none'}`, '');

  lines.push('## Practicals', '');
  lines.push('| Practical | Competencies | Status |', '|---|---|---|');
  for (const p of practicals) {
    lines.push(`| ${p.kind} ${p.id} | ${p.competencies.map((c) => `${c.id} ${c.depth}`).join(', ') || 'untagged'} | ${p.status ?? '-'} |`);
  }
  lines.push('');
  return lines.join('\n');
}

if (require.main === module) {
  const text = report(load());
  if (process.argv.includes('--write')) {
    fs.writeFileSync(OUT, `${text}\n`);
    console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
  } else {
    console.log(text);
  }
}

module.exports = { load, report };
